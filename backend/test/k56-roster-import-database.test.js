test('chạy lại cùng snapshot không tạo hàng hay UUID mới', async () => {
  const db = await setup();
  try {
    await applyRosterImport(testDatabase(db), payload(), 'pglite_test');
    const before = await snapshot(db);
    const rerun = { syncRunId: '102',
      summary: { syncRunId: '102', classMappingsToAdd: 0,
        rosterRowsToAdd: 0, testCount: 3 },
      expectedMappings: before.mappings.map(row => ({
      class_id: row.class_id, class_code: row.class_code
    })), expectedRoster: before.roster, newMappings: [], newRoster: [] };
    const result = await applyRosterImport(testDatabase(db), rerun, 'pglite_test');
    assert.equal(result.classMappingsAdded, 0);
    assert.equal(result.rosterRowsAdded, 0);
    assert.deepEqual(await snapshot(db), before);
  } finally { await db.close(); }
});

test('trùng khóa hoặc UUID bị chặn trước transaction', async () => {
  const db = await setup();
  try {
    const duplicate = payload();
    duplicate.newRoster.push({ ...duplicate.newRoster[0] });
    duplicate.summary.rosterRowsToAdd = 4;
    await assert.rejects(applyRosterImport(testDatabase(db), duplicate, 'pglite_test'),
      /DUPLICATE_NEW_ROSTER/);
    const duplicateRef = payload();
    duplicateRef.newRoster[0].student_ref = oldRows[0].student_ref;
    await assert.rejects(applyRosterImport(testDatabase(db), duplicateRef, 'pglite_test'),
      /DUPLICATE_NEW_STUDENT_REF/);
    assert.equal((await snapshot(db)).roster.length, 3);
  } finally { await db.close(); }
});

test('lớp ngoài phạm vi không đổi và học viên trùng tên vẫn tách theo ID', async () => {
  const db = await setup();
  try {
    await db.query(`INSERT INTO mapping.classroom_course_mapping
      (erp_course_class_id, erp_class_name_snapshot) VALUES (9999, 'IC9999')`);
    await db.query(`INSERT INTO assessment.term_test_roster VALUES ($1, 9999, 999,
      '00000000-0000-4000-8000-000000000099', 'Ngoài phạm vi')`, [slugs[0]]);
    const before = await snapshot(db);
    const input = payload();
    input.expectedMappings.push({ class_id: '9999', class_code: 'IC9999' });
    input.expectedRoster.push({ test_slug: slugs[0], class_id: '9999',
      contact_id: '999', student_ref: '00000000-0000-4000-8000-000000000099',
      student_name: 'Ngoài phạm vi' });
    input.newRoster.forEach(row => { row.student_name = 'Học viên giả A'; });
    await applyRosterImport(testDatabase(db), input, 'pglite_test');
    const after = await snapshot(db);
    assert.deepEqual(after.mappings.find(row => row.class_id === '9999'),
      before.mappings.find(row => row.class_id === '9999'));
    assert.deepEqual(after.roster.find(row => row.class_id === '9999'),
      before.roster.find(row => row.class_id === '9999'));
    assert.equal(after.roster.filter(row => row.student_name === 'Học viên giả A').length, 6);
  } finally { await db.close(); }
});

